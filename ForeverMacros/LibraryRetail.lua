local MO_HELP = "[@mouseover,help,nodead][help,nodead][@player]"
local MO_HARM = "[@mouseover,harm,nodead][]"
local FOCUS_HARM = "[@focus,harm,nodead][]"

local function Interrupt(id, fr, en)
  return { short = "Interruption", short_en = "Interrupt",
    title = "Interruption sur focus", title_en = "Focus interrupt",
    desc = fr or "Coupe ton incantation et interrompt ton focus, sinon ta cible.",
    desc_en = en or "Stops your cast and interrupts your focus, otherwise your target.",
    body = "#showtooltip\n/stopcasting\n/cast " .. FOCUS_HARM .. " {" .. id .. "}" }
end

local function Taunt(id)
  return { short = "Provocation", short_en = "Taunt",
    title = "Provocation au survol", title_en = "Mouseover taunt",
    desc = "Provoque l'ennemi survolé sans changer de cible, pratique pour récupérer un monstre.",
    desc_en = "Taunts the hovered enemy without switching target, handy to pick up a loose mob.",
    body = "#showtooltip\n/cast " .. MO_HARM .. " {" .. id .. "}" }
end

local function Cursor(short, short_en, title, title_en, id)
  return { short = short, short_en = short_en,
    title = title .. " sous le curseur", title_en = title_en .. " at cursor",
    desc = "Posé directement sous la souris, sans cercle de ciblage.",
    desc_en = "Dropped right under the mouse, no targeting circle.",
    body = "#showtooltip\n/cast [@cursor] {" .. id .. "}" }
end

local function MouseoverHelp(short, short_en, title, title_en, desc, desc_en, id)
  return { short = short, short_en = short_en,
    title = title .. " au survol", title_en = "Mouseover " .. title_en,
    desc = desc, desc_en = desc_en,
    body = "#showtooltip\n/cast " .. MO_HELP .. " {" .. id .. "}" }
end

