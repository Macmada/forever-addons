ns.lang = (GetLocale() == "frFR") and "fr" or "en"
ns.L = setmetatable({}, {
  __index = function(_, k)
    local t = (ns.lang == "en") and en or fr
    return t[k] or fr[k] or k
  end,
})

function ns.Pick(frText, enText)
  if ns.lang == "en" and enText then return enText end
  return frText
end
